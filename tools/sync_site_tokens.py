#!/usr/bin/env python3
"""Sync canonical Rubylight 7.0 tokens from rust/web/src/styles/tokens.css to site/tokens.css.

Usage:
    python tools/sync_site_tokens.py          # write site/tokens.css
    python tools/sync_site_tokens.py --check  # verify site/tokens.css is up to date
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "rust/web/src/styles/tokens.css"
DEST = ROOT / "site/tokens.css"

NOTE = "/* Generated by tools/sync_site_tokens.py from rust/web/src/styles/tokens.css. Do not edit. */"


def extract_block(css: str, header_pattern: str) -> list[tuple[str, str]]:
    match = re.search(header_pattern + r"\s*\{([^}]*)\}", css, re.MULTILINE | re.DOTALL)
    if not match:
        raise ValueError(f"Could not find CSS block matching {header_pattern!r} in {SRC}")
    props: list[tuple[str, str]] = []
    for line in match.group(1).splitlines():
        prop = re.match(r"^\s*(--[a-z0-9-]+)\s*:\s*([^;]+);", line)
        if prop:
            props.append((prop.group(1), " ".join(prop.group(2).strip().split())))
    if not props:
        raise ValueError(f"No custom properties parsed from {header_pattern!r}")
    return props


def generate(css: str | None = None) -> str:
    text = css if css is not None else SRC.read_text(encoding="utf-8")
    light_props = extract_block(text, r"^:root")
    dark_props = extract_block(text, r"^:root\[data-theme='dark'\]")

    lines = [
        NOTE,
        ":root {",
        "  color-scheme: light dark;",
    ]
    for name, value in light_props:
        lines.append(f"  {name}: {value};")
    lines.append("}")
    lines.append("")
    lines.append("@media (prefers-color-scheme: dark) {")
    lines.append("  :root {")
    for name, value in dark_props:
        lines.append(f"    {name}: {value};")
    lines.append("  }")
    lines.append("}")
    lines.append("")
    lines.append("@media (prefers-reduced-motion: reduce) {")
    lines.append("  :root {")
    lines.append("    --duration-fast: 0ms;")
    lines.append("    --duration-base: 0ms;")
    lines.append("    --duration-slow: 0ms;")
    lines.append("  }")
    lines.append("}")
    return "\n".join(lines) + "\n"


def check() -> bool:
    expected = generate()
    if not DEST.is_file():
        return False
    return DEST.read_text(encoding="utf-8") == expected


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    expected = generate()
    if "--check" in args:
        if not DEST.is_file() or DEST.read_text(encoding="utf-8") != expected:
            print(
                f"{DEST.relative_to(ROOT)} is out of sync with {SRC.relative_to(ROOT)}; "
                "run `python tools/sync_site_tokens.py`.",
                file=sys.stderr,
            )
            return 1
        return 0
    DEST.write_text(expected, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
